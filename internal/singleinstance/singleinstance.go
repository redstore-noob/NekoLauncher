// Package singleinstance 保证「同一个安装目录」同时只有一个启动器在运行。
//
// 作用域刻意绑定到 exe 所在目录，而不是全局唯一：
//
//   - 同一个文件夹被双击两次 → 第二次不再新开窗口，而是把已有窗口提到前台后退出；
//   - 不同文件夹的启动器 → 互不影响，可以同时运行。
//
// 后者是刻意的：把启动器复制成多份（例如一份便携版放 U 盘、一份装在本地）
// 是正当用法，全局单实例会把这种用法一并掐掉。
//
// 实现要点（Windows）：
//
//   - 用命名互斥体（CreateMutexW）做原子抢占；名字里带 exe 绝对路径的 hash，
//     因此天然按安装位置隔离。句柄活到进程结束，由内核在进程退出时释放，
//     不会留下需要手工清理的残留锁。
//   - 第二个实例不再自说自话地弹「已有实例」，而是激活已有窗口——用户双击
//     第二次的本来意图就是「把那个窗口给我拿出来」。
//   - 非 Windows 平台是 no-op：Wails 的 Linux/macOS 版本继续按原来的方式运行，
//     不引入平台相关的启动失败面。
package singleinstance

// Result 是一次单实例检查的结果。
type Result struct {
	// AlreadyRunning 为 true 表示同一个安装目录下已有实例在运行，
	// 调用方应当直接退出（本包已经尽力把已有窗口提到前台）。
	AlreadyRunning bool
	// Cleanup 释放互斥体句柄。调用方应 defer 它，且只在 AlreadyRunning
	// 为 false 时才有意义（已在运行时返回一个空操作函数）。
	Cleanup func()
}

// Acquire 尝试取得当前安装目录的唯一实例所有权。
//
// 返回的 Result 永远可用：即使内部出错也只会回落成「继续启动」，
// 绝不因为单实例检测本身把启动器挡在门外——这与仓库其它守卫逻辑
// （例如便携模式判定失败一律回落用户目录）保持同样的取向。
func Acquire() Result {
	return acquire()
}
