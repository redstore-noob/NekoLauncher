/*
 * 香港繁體中文（zh-HK）詞典。key 為簡體中文原文。
 *
 * 以 zh-TW 為基底，再把台灣用語改成香港用語（見下方 REPLACEMENTS）。
 * 少量香港獨有寫法可在 OVERRIDES 裡按簡體原文覆蓋。
 * 缺條目時 i18n 會回退原文，不會出現空白。
 */
import zhTW from "./zh-TW";

/** 台湾 → 香港的常用语替换表（按值替换，不动 key）
 *
 * 依据：维基百科 Module:CGroup/IT 的地区词转换表（陆/台/港三列对照），
 * 只收录「台湾写法与香港写法确实不同」且本项目文案里真实出现的词。
 *
 * 两点特别注意：
 * 1) 顺序敏感：长词必须排在短词前，否则「區域網路」会被「網路」先吃掉。
 * 2) 「程式」在台灣与香港都是通用写法（維基詞典：程式主臺灣、香港；
 *    程序主中國大陸），因此 zh-TW 的「程式」在 zh-HK 保持原樣，
 *    绝不可替换成「程序」——那是大陆用词。
 */
const REPLACEMENTS: Array<[RegExp, string]> = [
  // 网络类（长词优先）
  [/區域網路/g, "區域網絡"],
  [/子網路/g, "子網絡"],
  [/網際網路/g, "互聯網"],
  [/網路/g, "網絡"],
  // 硬件 / 系统
  [/伺服器/g, "服務器"],
  [/資料夾/g, "文件夾"],
  [/連接埠/g, "端口"],
  [/螢幕/g, "屏幕"],
  [/滑鼠/g, "鼠標"],
  [/隨身碟/g, "USB手指"],
  [/印表機/g, "打印機"],
  [/雷射/g, "激光"],
  // 资料 / 数据
  [/資料庫/g, "數據庫"],
  [/資料/g, "數據"],
  [/數位/g, "數碼"],
  [/位址/g, "地址"],
  // 软件 / 开发
  [/軟體/g, "軟件"],
  [/硬體/g, "硬件"],
  [/韌體/g, "固件"],
  [/執行緒/g, "線程"],
  [/函式/g, "函數"],
  [/變數/g, "變量"],
  [/解析度/g, "解像度"],
  // 交互（仅收录权威表确认港台有差异的词）
  [/使用者/g, "用戶"],
  [/上傳/g, "上載"],
  [/品質/g, "質素"],
  [/共享/g, "共用"],
  [/當機/g, "死機"],
];

/** 港台同形、无需替换的词（留作说明，避免以后被误加进上表）：
 * 「資訊」「影片」「設定」「檔案」「皮膚」在香港寫法相同。 */

/** 香港特有文案（原文 → 香港寫法），優先級高於批量替換 */
const OVERRIDES: Record<string, string> = {
  // 示例：外观/皮肤等词香港用「皮膚」與台灣一致，无需覆盖；
  // 后续发现台湾特有用词时在此按「简体原文」添加香港写法。
};

const zhHK: Record<string, string> = {};

for (const [key, value] of Object.entries(zhTW)) {
  let text = OVERRIDES[key] ?? value;

  for (const [pattern, replacement] of REPLACEMENTS) {
    text = text.replace(pattern, replacement);
  }
  zhHK[key] = text;
}

export default zhHK;
